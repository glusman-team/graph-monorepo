      assert html =~ "Corrupt stored document"
      assert html =~ "not valid base64"
      refute html =~ "{:error"
    end

    test "an unknown ?version names it in the corrupt copy", %{conn: conn, id: id} do
      {:ok, _view, html} = live(conn, "/edges/#{id}?version=nope-9.9.9")

      assert html =~ "Corrupt stored document"
      assert html =~ "does not store a version"
      assert html =~ "nope-9.9.9"
    end

    test "a hostile subject_name appears escaped and never as a live tag", %{conn: conn} do
      id = "22222222-2222-4222-8222-222222222222"
      base = Fixtures.resolved(Fixtures.edge_doc(Fixtures.first_edge_id()), @v1)
      hostile = Map.put(base, "subject_name", "<script>alert(1)</script>")

      Cosmos.Fake.seed(Fixtures.stored(id, %{@v1 => hostile}))

      {:ok, _view, html} = live(conn, "/edges/#{id}")

      assert html =~ "&lt;script&gt;alert(1)&lt;/script&gt;"
      refute html =~ "<script>alert(1)</script>"
    end
  end

  describe "the version diff" do
    test "shows an added field, a removed field and a changed value", %{conn: conn} do
      id = "33333333-3333-4333-8333-333333333333"

      v1 = %{
        "id" => id,
        "subject" => "CHEBI:64019",
        "subject_name" => "aspirin",
        "object" => "MONDO:0000418",
        "object_name" => "ischemic stroke",
        "predicate" => "biolink:treats",
        "number_of_cases" => 12,
        "knowledge_level" => "assertion",
        "publications" => ["PMID:1"]
      }

      v2 = %{
        "$t" => @v1,
        "$set" => %{"number_of_cases" => 42},
        "$add" => %{"publications" => ["PMID:2"]},
        "$del" => ["knowledge_level"]
      }

      Cosmos.Fake.seed(Fixtures.stored(id, %{@v1 => v1, @v2 => v2}))

      {:ok, _view, html} = live(conn, "/edges/#{id}")

      assert html =~ "changed from"
      assert html =~ "diff-line-added"
      assert html =~ "diff-line-removed"

      # Changed value: old and new, both visible, labelled rather than just coloured.
      assert html =~ ~s(class="diff-old")
      assert html =~ ">12</code>"
      assert html =~ ">42</code>"

      # Added list element and removed field, each in its reader's vocabulary.
      assert html =~ "PMID:2"
      assert html =~ "Knowledge level"
      assert html =~ "assertion"
    end

    test "a one-for-one object swap in a list renders as inner field lines, old struck first",
         %{conn: conn} do
      id = "33333333-3333-4333-8333-333333333334"

      source = fn urls ->
        %{
          "resource_id" => "infores:drugapprovals-kp",
          "resource_role" => "primary_knowledge_source",
          "source_record_urls" => urls
        }
      end

      v1 = %{
        "id" => id,
        "subject" => "CHEBI:64019",
        "subject_name" => "aspirin",
        "object" => "MONDO:0000418",
        "object_name" => "ischemic stroke",
        "predicate" => "biolink:treats",
        "sources" => [source.("https://old.example/a")]
      }

      v2 = %{
        "$t" => @v1,
        "$set" => %{"sources" => [source.("https://new.example/b")]}
      }

      Cosmos.Fake.seed(Fixtures.stored(id, %{@v1 => v1, @v2 => v2}))

      {:ok, _view, html} = live(conn, "/edges/#{id}")

      # The changed field is addressed by its full dotted path, so a sources list with
      # several sources still says whose field moved; the label is also the scope link,
      # carrying the top-level field key the panel can be narrowed to.
      assert html =~
               ~s(>sources.infores:drugapprovals-kp.source_record_urls</a>)

      assert html =~ ~s(class="diff-field diff-path")
      assert html =~ "change=sources"

      refute html =~ ~s("resource_role")
      refute html =~ "diff-parent"

      # Direction and shape: the previous version's value sits on the removed line, struck,
      # and the current version's on the added line below it. No arrow icon anywhere.
      assert html =~
               ~r/diff-line-removed[\s\S]{0,600}?diff-old">https:\/\/old\.example\/a</

      assert html =~
               ~r/diff-line-added[\s\S]{0,600}?diff-new">https:\/\/new\.example\/b</

      refute html =~ "diff-arrow"
    end

    test "a release that changed several fields can be scoped to one", %{conn: conn} do
      id = "66666666-6666-4666-8666-666666666666"

      v1 = %{
        "id" => id,
        "subject" => "CHEBI:64019",
        "subject_name" => "aspirin",
        "object" => "MONDO:0000418",
        "object_name" => "ischemic stroke",
        "predicate" => "biolink:treats",
        "number_of_cases" => 12,
        "publications" => ["PMID:1"]
      }

      v2 = %{
        "$t" => @v1,
        "$set" => %{"number_of_cases" => 42},
        "$add" => %{"publications" => ["PMID:2"]}
      }

      Cosmos.Fake.seed(Fixtures.stored(id, %{@v1 => v1, @v2 => v2}))

      # Unscoped: every field's change renders, and each label links to its own scope.
      {:ok, _view, html} = live(conn, "/edges/#{id}")
      assert html =~ "PMID:2"
      assert html =~ ">42</code>"
      assert html =~ "change=publications"
      assert html =~ "change=number_of_cases"

      # Scoped to the publications list: only its change renders, the summary still counts
      # the whole release, and the way back out is one link away.
      {:ok, _view, html} = live(conn, "/edges/#{id}?change=publications")
      assert html =~ "Showing only Product labels"
      assert html =~ "of the 2 fields changed"
      assert html =~ "PMID:2"
      refute html =~ ">42</code>"
      refute html =~ "change=number_of_cases"
      assert html =~ "Show every change"

      # A scope that matches nothing (a stale link) falls back to the full diff rather
      # than an empty panel.
      {:ok, _view, html} = live(conn, "/edges/#{id}?change=never_a_field")
      assert html =~ ">42</code>"
      refute html =~ "Showing only"
    end

    test "a single-version page has no Changes section at all", %{conn: conn} do
      id = "44444444-4444-4444-8444-444444444444"

      v1 = %{
        "id" => id,
        "subject" => "CHEBI:64019",
        "subject_name" => "aspirin",
        "object" => "MONDO:0000418",
        "object_name" => "ischemic stroke",
        "predicate" => "biolink:treats"
