  describe "the KG-scoped random button" do
    test "on an edge page the header button stays inside that graph and release", %{
      conn: conn,
      id: id
    } do
      {:ok, _view, html} = live(conn, "/edges/#{id}")

      # A reader looking at one graph who asks for a random edge expects another edge from
      # that graph, in the release they are reading (newest when the URL names none). A
      # button that could leave the store's current subject is a button nobody can trust, so
      # the scoping is worth an assertion of its own.
      assert html =~ ~s(href="/drugapprovals-kp/random?version=1.16.0")
      refute html =~ ~s(href="/drugapprovals-kp/random")
      refute html =~ ~s(href="/random")
    end

    test "a random click inside one release stays inside it, and switching versions re-pins", %{
      conn: conn,
      id: id
    } do
      {:ok, view, html} = live(conn, "/edges/#{id}?version=#{@v1}")

      # The pin is the release in the URL: random draws from exactly what the reader sees.
      assert html =~ ~s(href="/drugapprovals-kp/random?version=1.11.2")

      # Switching versions re-pins the button, so the next random click follows the reader.
      refute render_patch(view, "/edges/#{id}?version=#{@v2}") =~
               ~s(href="/drugapprovals-kp/random?version=1.11.2")

      assert render_patch(view, "/edges/#{id}?version=#{@v2}") =~
               ~s(href="/drugapprovals-kp/random?version=1.16.0")
    end

    test "the page names the graph once, in the asserts lead-in, with its source's external link",
         %{conn: conn, id: id} do
      {:ok, _view, html} = live(conn, "/edges/#{id}")

      # The name sits in the "asserts" lead-in above the sentence, not inside the claim:
      # the h1 is the relationship alone, so the name appears once at the top of the page.
      refute html =~ ~s(class="edge-kicker")

      assert html =~
               ~r/<p class="edge-asserts"><a[^>]*Multiomics-Drug-Approvals-KP[^>]*>DrugApprovals KP/

      refute html =~ ~r/<h1 class="edge-sentence"><a[^>]*Multiomics-Drug-Approvals-KP/

      # The name's single link is the source's own documentation, not a random pick.
      assert html =~
               ~s(href="https://github.com/NCATSTranslator/Translator-All/wiki/Multiomics-Drug-Approvals-KP")
    end

    test "a graph with no display config still scopes the button", %{conn: conn} do
      id = "00000000-0000-4000-8000-0000000000ff"

      Cosmos.Fake.seed(
        Fixtures.stored(id, %{
          "infores:unconfigured-kp-1.0.0" => %{
            "id" => id,
            "subject" => "a",
            "predicate" => "biolink:related_to",
            "object" => "b"
          }
        })
      )

      {:ok, view, html} = live(conn, "/edges/#{id}")

      assert html =~ ~s(href="/unconfigured-kp/random?version=1.0.0")
      # With no config there is no display name, so the canonical name is what a reader gets.
      assert html =~ "infores:unconfigured-kp"

      # The default config declares no asserts or footnote specs, so the page must not
      # render empty headed sections for them: a section exists only when it has content.
      refute html =~ ~s(class="edge-asserts")
      refute html =~ ~s(class="edge-tips")
      refute has_element?(view, "h2.section-title", "Tips")
      # Methods does render (the default config maps it to the assertion-method prose),
      # and it must have content, never an empty headed section.
      assert has_element?(view, "section.edge-methods h2.section-title", "Methods")
    end

    test "a page with no readable document keeps the button global", %{conn: conn} do
      id = "00000000-0000-4000-8000-0000000000fe"
      Cosmos.Fake.seed(%{"id" => id, "b" => "not-a-frame"})

      {:ok, _view, html} = live(conn, "/edges/#{id}")

      # There is no graph to scope to until a document has been read, so the button keeps its
      # whole-store meaning instead of linking to a slug nobody has established.
      assert html =~ ~s(href="/random")
    end
  end

